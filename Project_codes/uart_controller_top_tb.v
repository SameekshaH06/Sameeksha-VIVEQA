    //--------------------------------------------------

    send_string("HELLO");

    #1000000;

    $stop;

end
//////////////////////////////////////////////////////
// UART Receive Monitor
//////////////////////////////////////////////////////

initial
begin

    forever
    begin

        // Wait for Start Bit
        @(negedge uart_tx);

        #(BIT_TIME + BIT_TIME/2);

        // Read 8 data bits
        for(bit_index = 0; bit_index < 8; bit_index = bit_index + 1)
        begin
            rx_byte[bit_index] = uart_tx;
            #(BIT_TIME);
        end

        // Stop bit
        #(BIT_TIME);

        $write("%c", rx_byte);

    end

end
//////////////////////////////////////////////////////
// UART TX Monitor
//////////////////////////////////////////////////////
   always @(posedge clk)
begin
    if (DUT.tx_start)
        $display("TX Byte = %c (0x%h)", DUT.tx_data, DUT.tx_data);
end

endmodule


