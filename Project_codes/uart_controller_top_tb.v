module uart_controller_top_tb;

//////////////////////////////////////////////////////
// Signals
//////////////////////////////////////////////////////

reg clk;
reg rst;
reg uart_rx;

wire uart_tx;
wire control_out;
wire locked;
reg [7:0] rx_byte;
integer bit_index;

//////////////////////////////////////////////////////
// DUT
//////////////////////////////////////////////////////

uart_controller_top DUT
(
    .clk_24mhz(clk),
    .rst(rst),
    .uart_rx(uart_rx),

    .uart_tx(uart_tx),
    .control_out(control_out),
    .locked(locked)
);

//////////////////////////////////////////////////////
// 24 MHz Clock
//////////////////////////////////////////////////////

initial
begin
    clk = 0;
    forever #20.833 clk = ~clk;
end

//////////////////////////////////////////////////////
// UART Parameters
//////////////////////////////////////////////////////

localparam BIT_TIME = 8680; // ns (115200 baud)

//////////////////////////////////////////////////////
// UART Send Task
//////////////////////////////////////////////////////

task uart_send_byte;

input [7:0] data;

integer i;

begin

    // Start Bit

    uart_rx = 0;
    #(BIT_TIME);

    // Data Bits

    for(i=0;i<8;i=i+1)
    begin

        uart_rx = data[i];
        #(BIT_TIME);

    end

    // Stop Bit

    uart_rx = 1;
    #(BIT_TIME);

end

endtask

//////////////////////////////////////////////////////
// Send String Task
//////////////////////////////////////////////////////

task send_string;

input [8*16-1:0] str;

integer j;

begin

    for(j=15;j>=0;j=j-1)
    begin

        if(str[j*8 +: 8] != 8'd0)
            uart_send_byte(str[j*8 +:8]);

    end

    // ENTER

    uart_send_byte(8'h0D);

end

endtask

